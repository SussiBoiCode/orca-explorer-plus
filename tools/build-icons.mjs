// Regenerates panel/icons.js from Orca's own file-type icon tables and lucide-static SVGs, so
// Explorer+ shows the same icons as Orca's built-in explorer.
//
//   node tools/build-icons.mjs <orca checkout>/src/renderer/src/lib <lucide-static package dir>
//
// Use the lucide-static version matching Orca's lucide-react (see Orca's package.json).
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const [libDir, lucideDir] = process.argv.slice(2)
if (!libDir || !lucideDir) {
  console.error('usage: node tools/build-icons.mjs <orca lib dir> <lucide-static dir>')
  process.exit(2)
}

function table(file, exportName) {
  const src = readFileSync(path.join(libDir, file), 'utf8')
  const start = src.indexOf(`export const ${exportName}`)
  const body = src.slice(src.indexOf('{', start) + 1, src.indexOf('\n}', start))
  const out = {}
  for (const m of body.matchAll(/^\s*('([^']+)'|([A-Za-z0-9_]+)):\s*([A-Za-z0-9]+),?\s*$/gm)) {
    out[m[2] ?? m[3]] = m[4]
  }
  return out
}

function compound() {
  const src = readFileSync(path.join(libDir, 'file-type-icon-extension-table.ts'), 'utf8')
  const m = src.match(/COMPOUND_EXTENSIONS[^=]*=\s*\[([\s\S]*?)\]/)
  return m ? [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : []
}

const byExt = table('file-type-icon-extension-table.ts', 'FILE_ICON_BY_EXTENSION')
const byName = table('file-type-icon-name-table.ts', 'FILE_ICON_BY_NAME')

// lucide-react component name -> lucide-static file name (FileCode -> file-code, FileAxis3D -> file-axis-3d).
const kebab = (name) =>
  name
    .replace(/([a-z])([A-Z0-9])/g, '$1-$2')
    .replace(/([0-9])([A-Z])/g, '$1-$2')
    .toLowerCase()

const extra = [
  'File', 'FileCog', 'FileLock', 'FileTerminal', 'Folder', 'FolderOpen', 'ChevronRight', 'Link',
  'Loader2:loader-circle', 'CircleAlert', 'ArrowUpDown', 'Plus', 'FilePlus', 'FolderPlus', 'RefreshCw',
  'ListCollapse', 'ListFilter', 'X', 'ArrowLeft', 'Copy', 'Pencil', 'Trash2', 'ExternalLink', 'Focus',
  'Check', 'ArrowUp', 'ArrowDown', 'Maximize2', 'ChevronDown'
]

const icons = {}
for (const spec of [...new Set([...Object.values(byExt), ...Object.values(byName), ...extra])]) {
  const [name, fileOverride] = spec.split(':')
  const file = path.join(lucideDir, 'icons', `${fileOverride ?? kebab(name)}.svg`)
  const svg = readFileSync(file, 'utf8')
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).trim().replace(/\s*\n\s*/g, '')
  icons[name] = inner
}

const here = path.dirname(fileURLToPath(import.meta.url))
const out = `// Generated by tools/build-icons.mjs from Orca's file-type icon tables and lucide-static
// (ISC License, see vendor/LUCIDE-LICENSE.txt). Do not edit by hand.
export const ICONS = ${JSON.stringify(icons)}
export const FILE_ICON_BY_EXTENSION = ${JSON.stringify(byExt)}
export const FILE_ICON_BY_NAME = ${JSON.stringify(byName)}
export const COMPOUND_EXTENSIONS = ${JSON.stringify(compound())}
`
writeFileSync(path.join(here, '..', 'panel', 'icons.js'), out)
console.log(`wrote panel/icons.js: ${Object.keys(icons).length} icons, ${Object.keys(byExt).length} extensions, ${Object.keys(byName).length} names`)
